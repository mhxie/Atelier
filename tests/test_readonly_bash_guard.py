class BlockedSubcommandsTest(unittest.TestCase):
    def test_worktree_moves_are_found(self) -> None:
        for command in DENIED:
            self.assertTrue(guard.blocked_subcommands(command), command)

    def test_reads_pass(self) -> None:
        for command in ALLOWED:
            self.assertEqual(guard.blocked_subcommands(command), [], command)

    def test_unbalanced_quotes_still_scan(self) -> None:
        self.assertEqual(guard.blocked_subcommands("git stash 'oops"), ["stash"])

    def test_unreadable_shell_input_is_named_unscannable_once(self) -> None:
        for command in ('eval "$CMD"', "bash x.sh", "bash < script.sh", "cat x.sh | bash"):
            self.assertEqual(guard.blocked_subcommands(command), [guard.UNSCANNABLE], command)

    def test_interpreter_text_is_matched_only_when_shelling_out(self) -> None:
        self.assertEqual(guard.blocked_subcommands("python3 -c \"os.system('git reset')\""), ["reset"])
        self.assertEqual(guard.blocked_subcommands("python3 -c \"print('git reset')\""), [])
        self.assertEqual(guard.blocked_subcommands("python3 -c \"subprocess.run(['reset', 'git'])\""), [])

    def test_brace_expansion_matches_the_shell(self) -> None:
        self.assertEqual(guard._brace_expand("a{b,c}d"), ["abd", "acd"])
        self.assertEqual(guard._brace_expand("x{,.bak}"), ["x", "x.bak"])
        self.assertEqual(guard._brace_expand("f{1..3}"), ["f1", "f2", "f3"])
        self.assertEqual(guard._brace_expand("{a,{b,c}}"), ["a", "b", "c"])

    def test_writes_name_their_target_and_the_repo_root_is_honoured(self) -> None:
        self.assertEqual(guard.blocked_subcommands("echo x > scripts/a.py", repo="/repo"), ["write:scripts/a.py"])
        self.assertEqual(guard.blocked_subcommands("echo x >| scripts/a.py", repo="/repo"), ["write:scripts/a.py"])
        self.assertEqual(guard.blocked_subcommands("echo x >>scripts/a.py", repo="/repo"), ["write:scripts/a.py"])
        self.assertEqual(guard.blocked_subcommands("echo x > /repo/scripts/a.py", repo="/repo"), ["write:/repo/scripts/a.py"])
        self.assertEqual(guard.blocked_subcommands("echo x > /elsewhere/a.py", repo="/repo"), [])
        # ~ expands from HOME; an unknown HOME makes the target unscannable
        self.assertEqual(guard.blocked_subcommands("echo x > ~/repo/a.py", repo="/home/u/repo", cwd="/tmp", env={"HOME": "/home/u"}), ["write:~/repo/a.py"])
        self.assertEqual(guard.blocked_subcommands("echo x > ~/other/a.py", repo="/home/u/repo", cwd="/tmp", env={"HOME": "/home/u"}), [])
        self.assertEqual(guard.blocked_subcommands("echo x > ~/a.py", repo="/repo", cwd="/repo", env={}), [guard.UNSCANNABLE])
        # a prefix assignment scopes to its command and does not change the same line's expansion
        self.assertEqual(
            guard.blocked_subcommands('CLAUDE_PROJECT_DIR=/tmp echo x > "$CLAUDE_PROJECT_DIR/scripts/a.py"', repo="/repo", cwd="/repo", env={"CLAUDE_PROJECT_DIR": "/repo"}),
            ["write:$CLAUDE_PROJECT_DIR/scripts/a.py"],
        )
        # PWD follows cd
        self.assertEqual(guard.blocked_subcommands('cd /repo && echo x > "$PWD/a.py"', repo="/repo", cwd="/tmp", env={}), ["write:$PWD/a.py"])
        self.assertEqual(guard.blocked_subcommands('cd /tmp && echo x > "$PWD/a.py"', repo="/repo", cwd="/repo", env={}), [])
        # a tilde stored in a variable expands at assignment time
        self.assertEqual(guard.blocked_subcommands('T=~; echo x > "$T/a.py"', repo="/repo", cwd="/tmp", env={"HOME": "/repo"}), ["write:$T/a.py"])
        self.assertEqual(guard.blocked_subcommands('T=~; echo x > "$T/a.py"', repo="/repo", cwd="/tmp", env={"HOME": "/home/u"}), [])
        # assignments apply in execution order
        self.assertEqual(
            guard.blocked_subcommands('A=/tmp; echo x > "$A/first"; A=scripts; echo x > "$A/second"', repo="/repo", cwd="/repo", env={}),
            ["write:$A/second"],
        )
        # variables resolve from the given environment; PWD is the cwd
        self.assertEqual(
            guard.blocked_subcommands('cp /tmp/a "$P/scripts/a.py"', repo="/repo", cwd="/repo", env={"P": "/repo"}),
            ["write:$P/scripts/a.py"],
        )
        self.assertEqual(guard.blocked_subcommands('cp /tmp/a "$P/a.py"', repo="/repo", cwd="/repo", env={"P": "/elsewhere"}), [])
        self.assertEqual(guard.blocked_subcommands('cp /tmp/a "$PWD/a.py"', repo="/repo", cwd="/repo/sub", env={}), ["write:$PWD/a.py"])
        self.assertEqual(guard.blocked_subcommands('cp /tmp/a "$Q/a.py"', repo="/repo", cwd="/repo", env={}), [guard.UNSCANNABLE])
        # relative paths resolve from cwd, so ../ can leave or stay inside the repo
        self.assertEqual(guard.blocked_subcommands("echo x > ../outside.txt", repo="/repo", cwd="/repo"), [])
        self.assertEqual(guard.blocked_subcommands("echo x > ../a.py", repo="/repo", cwd="/repo/sub"), ["write:../a.py"])
        # a checkout under a scratch root is still the repository
        self.assertEqual(guard.blocked_subcommands("echo x > /tmp/atelier/scripts/a.py", repo="/tmp/atelier"), ["write:/tmp/atelier/scripts/a.py"])
        self.assertEqual(guard.blocked_subcommands("echo x > /tmp/other/a.py", repo="/tmp/atelier"), [])

